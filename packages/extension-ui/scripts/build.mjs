// Standalone, standard-library-only generator. Never edit dist CSS by hand.
import {readFile, writeFile, mkdir} from 'node:fs/promises';
import path from 'node:path';
import {pathToFileURL} from 'node:url';

const root = path.resolve(import.meta.dirname, '..');
export async function buildUI({out = path.join(root, 'dist'), check = false} = {}) {
  const tokens = JSON.parse(await readFile(path.join(root, 'tokens/tokens.json'), 'utf8'));
  const banner = '/* SPDX-License-Identifier: Apache-2.0\n * Generated by scripts/build.mjs; do not edit. */\n';
  const declarations = Object.entries(tokens).map(([key, value]) => {
    if (!/^[a-z][a-z0-9-]+$/.test(key) || typeof value !== 'string' || /[;{}\n]/.test(value)) {
      throw Error('Invalid CSS token: ' + key);
    }
    return `  --sp-${key}: ${value};`;
  }).join('\n');
  const components = await readFile(path.join(root, 'styles/components.css'), 'utf8');
  const files = {'tokens.css': banner + `[data-sp-ui] {\n${declarations}\n}\n`, 'components.css': banner + components};
  if (!check) await mkdir(out, {recursive: true});
  for (const [file, content] of Object.entries(files)) {
    const dest = path.join(out, file);
    if (check) {
      const actual = await readFile(dest, 'utf8');
      if (actual !== content) throw Error('Generated CSS drift: ' + dest);
    } else await writeFile(dest, content);
  }
  return Object.keys(files);
}

if (process.argv[1] && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href) {
  const index = process.argv.indexOf('--out');
  if (index !== -1 && !process.argv[index + 1]) throw Error('--out requires a directory');
  await buildUI({out: index === -1 ? undefined : path.resolve(process.argv[index + 1]), check: process.argv.includes('--check')});
}
